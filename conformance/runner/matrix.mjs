#!/usr/bin/env node
// Regenerates MATRIX.md from results/ + ledgers/. Every cell is an executed
// outcome — never a claim. `--check` compares the regenerated matrix to the
// checked-in file and fails if stale.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { CONFORMANCE, readJson, fail, ok } from './lib.mjs'

const manifest = readJson(resolve(CONFORMANCE, 'wfsdk', 'manifest.json'))
const sdks = readdirSync(resolve(CONFORMANCE, 'results'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort()
const results = Object.fromEntries(sdks.map((s) => [s, readJson(resolve(CONFORMANCE, 'results', `${s}.json`))]))

const revisions = new Set(sdks.map((s) => results[s].corpusRevision))
if (revisions.size > 1)
  fail(`results are not comparable: mixed corpus revisions ${[...revisions].join(', ')} — re-run run.mjs`)
const revision = [...revisions][0] ?? 'none'

const CELL = { PASS: '✅ pass', FAIL: '❌ FAIL', SKIP: '⏭ todo', MISSING: '∅ missing' }
const lines = []
lines.push('# SDK Conformance Matrix')
lines.push('')
lines.push(`| case | level | ${sdks.join(' | ')} |`)
lines.push(`| --- | --- | ${sdks.map(() => '---').join(' | ')} |`)
for (const c of manifest.cases) {
  const cells = sdks.map((s) => {
    const o = results[s].outcomes[c.id]
    if (!o) return '∅ missing'
    return o.outcome === 'SKIP' ? `⏭ ${o.excuse}` : CELL[o.outcome]
  })
  lines.push(`| ${c.id} | ${c.level} | ${cells.join(' | ')} |`)
}
lines.push('')
const totals = sdks.map((s) => {
  const t = results[s].summary
  return `**${s}**: ${t.PASS}/${manifest.cases.length} pass` + (t.FAIL ? `, ${t.FAIL} fail` : '') + (t.SKIP ? `, ${t.SKIP} todo` : '') + (t.MISSING ? `, ${t.MISSING} missing` : '')
})
lines.push(totals.join(' · '))
lines.push('')
lines.push(`Generated by \`conformance/runner/matrix.mjs\` from \`results/\` at corpus revision \`${revision}\` — do not edit by hand.`)
lines.push('')
const rendered = lines.join('\n')

const target = resolve(CONFORMANCE, 'MATRIX.md')
if (process.argv.includes('--check')) {
  let existing = ''
  try { existing = readFileSync(target, 'utf8') } catch {}
  if (existing !== rendered) fail('MATRIX.md is stale — regenerate with: node conformance/runner/matrix.mjs')
  else ok('MATRIX.md is current')
} else {
  writeFileSync(target, rendered)
  ok(`MATRIX.md regenerated at corpus revision ${revision}`)
}
