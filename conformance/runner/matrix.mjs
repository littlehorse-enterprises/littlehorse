#!/usr/bin/env node
// MATRIX.md from results/: every cell an executed outcome, never a claim.
// `--check` fails when the checked-in matrix is stale.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { CONFORMANCE, readJson, fail, ok } from './lib.mjs'

const wfsdkManifest = readJson(resolve(CONFORMANCE, 'areas', 'wfsdk', 'manifest.json'))
const serdeManifest = readJson(resolve(CONFORMANCE, 'areas', 'serde', 'manifest.json'))
const rows = [
  ...wfsdkManifest.cases.map((c) => ({ area: 'wfsdk', ...c })),
  ...serdeManifest.cases.map((c) => ({ area: 'serde', ...c })),
]
const sdks = readdirSync(resolve(CONFORMANCE, 'results'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort()
const results = Object.fromEntries(sdks.map((s) => [s, readJson(resolve(CONFORMANCE, 'results', `${s}.json`))]))

const revisions = new Set(sdks.map((s) => results[s].corpusRevision))
if (revisions.size > 1)
  fail(`results are not comparable: mixed corpus revisions ${[...revisions].join(', ')} — re-run run.mjs`)
const revision = [...revisions][0] ?? 'none'

// GitHub strips styled markup from markdown — glyph is the only color channel.
const CELL = { PASS: '✅ pass', FAIL: '❌ FAIL', MISSING: '🟥 missing' }
const SKIP_CELL = { todo: '🟡 todo', not_applicable: '➖ n/a' }
const lines = []
lines.push('# SDK Conformance Matrix')
for (const area of [...new Set(rows.map((r) => r.area))]) {
  const areaRows = rows.filter((r) => r.area === area)
  lines.push('')
  lines.push(`## ${area}`)
  lines.push('')
  lines.push(`| case | level | ${sdks.join(' | ')} |`)
  lines.push(`| --- | --- | ${sdks.map(() => '---').join(' | ')} |`)
  const tally = Object.fromEntries(sdks.map((s) => [s, { PASS: 0, FAIL: 0, SKIP: 0, MISSING: 0 }]))
  for (const c of areaRows) {
    const cells = sdks.map((s) => {
      const o = results[s].outcomes[c.id]
      if (!o) { tally[s].MISSING++; return CELL.MISSING }
      tally[s][o.outcome]++
      return o.outcome === 'SKIP' ? SKIP_CELL[o.excuse] : CELL[o.outcome]
    })
    lines.push(`| ${c.id} | ${c.level} | ${cells.join(' | ')} |`)
  }
  lines.push('')
  lines.push(sdks.map((s) => {
    const t = tally[s]
    return `**${s}**: ${t.PASS}/${areaRows.length} pass` + (t.FAIL ? `, ${t.FAIL} fail` : '') + (t.SKIP ? `, ${t.SKIP} todo` : '') + (t.MISSING ? `, ${t.MISSING} missing` : '')
  }).join(' · '))
}
lines.push('')
const totals = sdks.map((s) => {
  const t = results[s].summary
  return `**${s}**: ${t.PASS}/${rows.length} pass` + (t.FAIL ? `, ${t.FAIL} fail` : '') + (t.SKIP ? `, ${t.SKIP} todo` : '') + (t.MISSING ? `, ${t.MISSING} missing` : '')
})
lines.push(`**Overall** — ${totals.join(' · ')}`)
lines.push('')
lines.push(`Generated by \`conformance/runner/matrix.mjs\` from \`results/\` at corpus revision \`${revision}\` — do not edit by hand.`)
lines.push('')
const rendered = lines.join('\n')

const target = resolve(CONFORMANCE, 'MATRIX.md')
if (process.argv.includes('--check')) {
  let existing = ''
  try { existing = readFileSync(target, 'utf8') } catch {}
  if (existing !== rendered) fail('MATRIX.md is stale — regenerate with: node conformance/runner/matrix.mjs')
  else ok('MATRIX.md is current')
} else {
  writeFileSync(target, rendered)
  ok(`MATRIX.md regenerated at corpus revision ${revision}`)
}
